// Arena looks. Each round's seed picks one, so every duel travels somewhere
// new and both multiplayer phones see the same place. One dominant hue per
// arena with fog doing the painterly depth; the foreground stays dark so the
// black stickmen read as silhouettes against a lit background.

export type Weather = 'pollen' | 'dust' | 'snow' | 'embers' | 'fireflies' | 'rain' | 'spores';

// Which set dressing the map uses: hand-built set pieces (forest, town,
// colosseum) or the open landscape (mountains, trees, clouds).
export type Decor = 'forest' | 'town' | 'colosseum' | 'wild';

export type Theme = {
  id: string;
  name: string;
  decor: Decor;
  ambience: 'forest' | 'rain' | 'fire' | null;
  ledgeTop: string; // walkable top of the cliffs
  ledgeLip: string; // bright rim along the cliff edge (grass, snow, sand)
  skyTop: string;
  skyHorizon: string;
  sun: string;
  sunDir: [number, number, number]; // direction TO the sun
  sunIntensity: number;
  hemiSky: string;
  hemiGround: string;
  hemiIntensity: number;
  rim: string; // back light that outlines the black figures
  fog: string;
  fogNear: number;
  fogFar: number;
  ground: string;
  groundFar: string;
  rock: string; // pillars / cliffs
  rockDark: string;
  mountains: [string, string, string]; // near → far
  foliage: string;
  foliageDark: string;
  trunk: string;
  cloud: string;
  cloudOpacity: number;
  weather: Weather;
  weatherColor: string;
  trees: 'pine' | 'round' | 'dead' | 'mushroom';
  lava?: string;
  moon?: boolean;
};

