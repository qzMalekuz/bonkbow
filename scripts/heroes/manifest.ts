// Writes src/game3d/heroAssets.ts: a static require() for every baked hero
// file in assets/heroes/ (Metro needs literal paths). Run by build.sh.
import { readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../../', import.meta.url));
const files = readdirSync(`${ROOT}assets/heroes`).sort();
const ids = files.filter((f) => f.endsWith('_heads.json')).map((f) => f.replace('_heads.json', ''));
const lines = ids.map((id) =>
  [
    `  ${id}: {`,
    `    heads: require('../../assets/heroes/${id}_heads.png'),`,
    `    meta: require('../../assets/heroes/${id}_heads.json'),`,
    `    body: require('../../assets/heroes/${id}_body.json'),`,
    `  },`,
  ].join('\n'),
);
writeFileSync(
  `${ROOT}src/game3d/heroAssets.ts`,
  `// Generated by scripts/heroes/manifest.ts (run scripts/heroes/build.sh). Do not edit.
import type { FaceId } from '@/game/faces';

// heads: atlas of the sheet's head drawings (sprites.py); meta: its tile
// order and head frame; body: the baked chibi suit (bake.ts).
export const HERO_ASSETS: Record<FaceId, { heads: number; meta: unknown; body: unknown }> = {
${lines.join('\n')}
};
`,
);
console.log(`heroAssets.ts: ${ids.length} heroes`);
